import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')
const timeState = await readFile(resolve(root, 'packages/core/src/time-state.mjs'), 'utf8')
const sourceSvg = await readFile(resolve(root, '图标/DeepSeek.svg'), 'utf8')
const hermesTemplate = await readFile(resolve(root, 'adapters/hermes/plugin.template.js'), 'utf8')
const dshTemplate = await readFile(resolve(root, 'adapters/dsh/client.template.js'), 'utf8')
const dshHostTemplate = await readFile(resolve(root, 'adapters/dsh/host.template.mjs'), 'utf8')
const pathMatch = sourceSvg.match(/<path[^>]*\sd="([^"]+)"/)
if (pathMatch === null) throw new Error('Unable to find the DeepSeek mark path in 图标/DeepSeek.svg')
const mark = `/** Generated from 图标/DeepSeek.svg. Do not edit manually. */\n\nexport const DEEPSEEK_MARK_PATH = ${JSON.stringify(pathMatch[1])}\n`
const browserTimeState = `${timeState.replace(/^export /gm, '')}\n\nglobalThis.DeepSeekTime = { BEIJING_TIME_ZONE, IDLE_COLOR, PEAK_COLOR, formatRemainingTime, getDeepSeekTimeState }\n`
const hermesPlugin = `/** Generated by scripts/stage-adapters.mjs. Do not edit manually. */\n\n${timeState.replace(/^export /gm, '')}\n${mark.replace(/^export /gm, '')}\n${hermesTemplate}`
const dshBundle = `/** Generated by scripts/stage-adapters.mjs. Do not edit manually. */\n\n${timeState.replace(/^export /gm, '')}\n${mark.replace(/^export /gm, '')}\n${dshTemplate}`

const targets = [
  ['packages/core/src/deepseek-mark.mjs', mark],
  ['adapters/hermes/plugin.js', hermesPlugin],
  ['adapters/hermes/time-state.mjs', timeState],
  ['adapters/hermes/deepseek-mark.mjs', mark],
  ['adapters/dsh/src/time-state.mjs', timeState],
  ['adapters/dsh/src/deepseek-mark.mjs', mark],
  ['adapters/dsh/lib/client.js', dshBundle],
  ['adapters/dsh/lib/index.js', dshHostTemplate],
  ['adapters/codex/deepseek-time/time-state.mjs', timeState],
  ['adapters/codex/deepseek-time/time-state.browser.js', browserTimeState],
  ['adapters/codex/deepseek-time/deepseek-mark.mjs', mark],
]

let stale = false
for (const [relativePath, expected] of targets) {
  const target = resolve(root, relativePath)
  let actual
  try {
    actual = await readFile(target, 'utf8')
  } catch {
    actual = undefined
  }
  if (actual === expected) continue
  stale = true
  if (!checkOnly) {
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, expected, 'utf8')
  }
}

if (checkOnly && stale) {
  throw new Error('Generated adapter files are stale. Run: npm run build')
}
